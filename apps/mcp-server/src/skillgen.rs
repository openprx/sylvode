/// Everything `--lint` looks at.
pub struct LintInput<'a> {
    pub catalogue: &'a Catalogue<'a>,
    /// The names the registry registers, in any order.
    pub registry_names: &'a [String],
    /// The names of the search mode entry tools.
    pub entry_names: &'a [&'a str],
    /// `SKILL.md` and `recipes/install.md`: the hand-written skill text.
    pub hand_written: &'a [(&'static str, &'a str)],
    /// The generated outputs (what `--write` would produce).
    pub outputs: &'a [Output],
    /// `.lint-allow`.
    pub allow: &'a str,
}

fn parse_allow(allow: &str, problems: &mut Vec<String>) -> Vec<String> {
    let mut tokens = Vec::new();
    for (number, line) in allow.lines().enumerate() {
        let line = line.trim();
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        match line.split_once('#') {
            Some((token, reason)) if !token.trim().is_empty() && !reason.trim().is_empty() => {
                tokens.push(token.trim().to_string());
            }
            _ => problems.push(format!(
                "{}:{}: an allowlist entry needs `token # reason`",
                paths::LINT_ALLOW,
                number + 1
            )),
        }
    }
    tokens
}

/// The single-line code spans of `text`.
fn code_spans(text: &str) -> Vec<&str> {
    text.lines()
        .flat_map(|line| line.split('`').skip(1).step_by(2))
        .collect()
}

fn looks_like_a_tool_name(token: &str) -> bool {
    crate::tools::schema_check::KNOWN_PATTERNS
        .iter()
        .find(|(pattern, _)| *pattern == r"^[a-z_]+(\.[a-z_]+)+$")
        .is_some_and(|(_, matches)| matches(token))
        || (token.starts_with("sylvode_") && token.chars().all(|c| c.is_ascii_lowercase() || c == '_'))
}

fn has_uuid(text: &str) -> bool {
    let bytes = text.as_bytes();
    bytes.windows(36).any(|window| {
        window.iter().enumerate().all(|(index, byte)| match index {
            8 | 13 | 18 | 23 => *byte == b'-',
            _ => byte.is_ascii_hexdigit(),
        })
    })
}

fn has_bot_token(text: &str) -> bool {
    text.match_indices("opr_").any(|(index, _)| {
        text.get(index + 4..)
            .is_some_and(|rest| rest.chars().take_while(char::is_ascii_hexdigit).count() >= 8)
    })
}

fn machine_specific(text: &str) -> Vec<&'static str> {
    let mut found = Vec::new();
    for needle in ["/Users/", "/home/", "C:\\", "http://127.", "localhost:"] {
        if text.contains(needle) {
            found.push(needle);
        }
    }
    if has_uuid(text) {
        found.push("a UUID");
    }
    if has_bot_token(text) {
        found.push("an opr_ token");
    }
    found
}

/// The hand-written checks of `--lint`. An empty list means the skill and the catalogue agree.
pub fn lint(input: &LintInput<'_>) -> Vec<String> {
    let mut problems = Vec::new();

    // (a) Every backticked tool-shaped token of the hand-written text names a tool.
    let allow = parse_allow(input.allow, &mut problems);
    let known = input
        .registry_names
        .iter()
        .map(String::as_str)
        .chain(input.entry_names.iter().copied())
        .collect::<BTreeSet<_>>();
    let mut allow_used = BTreeSet::new();
    for (path, text) in input.hand_written {
        for span in code_spans(text) {
            if !looks_like_a_tool_name(span) || known.contains(span) {
                continue;
            }
            if allow.iter().any(|token| token == span) {
                allow_used.insert(span);
            } else {
                problems.push(format!(
                    "{path}: `{span}` looks like a tool name but is not a registry or entry tool"
                ));
            }
        }
    }
    for token in &allow {
        if !allow_used.contains(token.as_str()) {
            problems.push(format!(
                "{}: `{token}` is allowed but no longer used",
                paths::LINT_ALLOW
            ));
        }
    }

    // (b) No machine-specific content in generated or hand-written skill files.
    let skill_files = input
        .outputs
        .iter()
        .filter(|output| output.path.starts_with("skills/"))
        .map(|output| (output.path, output.content.as_str()))
        .chain(input.hand_written.iter().copied());
    for (path, text) in skill_files {
        for found in machine_specific(text) {
            problems.push(format!("{path}: contains {found}"));
        }
    }

    // (c) The registry and the catalogue name the same tools, once each.
    let mut seen = BTreeSet::new();
    for entry in input.catalogue.catalog {
        if !seen.insert(entry.name) {
            problems.push(format!("the catalogue has two entries for {}", entry.name));
        }
    }
    let registry = input.registry_names.iter().map(String::as_str).collect::<BTreeSet<_>>();
    for name in registry.difference(&seen) {
        problems.push(format!("registry tool {name} has no catalogue entry"));
    }
    for name in seen.difference(&registry) {
        problems.push(format!("catalogue entry {name} is not a registry tool"));
    }

    // (d) Every category is used.
    for category in input.catalogue.categories {
        if !input
            .catalogue
            .catalog
            .iter()
            .any(|entry| entry.category == category.name)
        {
            problems.push(format!("category {} has no tool", category.name));
        }
    }
    for entry in input.catalogue.catalog {
        if !input
            .catalogue
            .categories
            .iter()
            .any(|category| category.name == entry.category)
        {
            problems.push(format!("{} uses the unknown category {}", entry.name, entry.category));
        }
    }

    // (e) Summaries are short and have no trailing period.
    for entry in input.catalogue.catalog {
        if entry.summary.chars().count() > SUMMARY_MAX_CHARS || entry.summary.ends_with('.') || entry.summary.is_empty()
        {
            problems.push(format!(
                "the summary of {} is empty, too long or ends with a period",
                entry.name
            ));
        }
    }

    // Size contracts of two generated texts.
    for output in input.outputs {
        if output.path == paths::SERVER_INSTRUCTIONS
            && !SERVER_INSTRUCTIONS_LINES.contains(&output.content.lines().count())
        {
            problems.push(format!(
                "{} must have {} to {} lines",
                output.path,
                SERVER_INSTRUCTIONS_LINES.start(),
                SERVER_INSTRUCTIONS_LINES.end()
            ));
        }
        if output.path == paths::SKILL_MD {
            let block = tool_overview_block(input.catalogue);
            if block.lines().count() >= OVERVIEW_BLOCK_MAX_LINES {
                problems.push(format!("the tool-overview block has {} lines", block.lines().count()));
            }
        }
    }
    problems
}

