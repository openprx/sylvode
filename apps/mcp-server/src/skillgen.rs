    fn lint_with(skill: &str, allow: &str, catalogue: &Catalogue<'_>, registry: &[&str]) -> Vec<String> {
        let registry = registry.iter().map(ToString::to_string).collect::<Vec<_>>();
        let outputs = generated();
        lint(&LintInput {
            catalogue,
            registry_names: &registry,
            entry_names: &["sylvode_search"],
            hand_written: &[(paths::SKILL_MD, skill)],
            outputs: &outputs,
            allow,
        })
    }

