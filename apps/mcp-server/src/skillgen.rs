    #[test]
    fn lint_a_flags_a_token_that_names_no_tool_and_honours_the_allowlist() {
        let registry = ["alpha.list", "alpha.make", "sylvode_task_get"];
        let skill = format!("{SKILL}\nUse `alpha.gone`, `sylvode_search` and `source.field`.\n");
        let problems = lint_with(&skill, "", &catalogue(), &registry);
        assert_eq!(problems.len(), 2, "{problems:?}");
        assert!(
            problems.iter().any(|p| p.contains("`alpha.gone`"))
                && problems.iter().any(|p| p.contains("`source.field`"))
        );
        let allowed = lint_with(
            &skill,
            "source.field # a field of the task view\nalpha.gone # reason\n",
            &catalogue(),
            &registry,
        );
        assert!(allowed.is_empty(), "{allowed:?}");
        let stale = lint_with(SKILL, "source.field # unused\n", &catalogue(), &registry);
        assert!(stale.iter().any(|p| p.contains("no longer used")), "{stale:?}");
        let no_reason = lint_with(SKILL, "source.field\n", &catalogue(), &registry);
        assert!(
            no_reason.iter().any(|p| p.contains("needs `token # reason`")),
            "{no_reason:?}"
        );
    }

