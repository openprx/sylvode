fn agents_overview_block(catalogue: &Catalogue<'_>) -> String {
    let mut block = format!("- The tool catalogue has {}:\n", tool_sentence(catalogue));
    for category in catalogue.categories {
        let (reads, total) = counts(catalogue, category.name);
        let _ = writeln!(
            block,
            "  - `{}` ({} {}, {} read, {} write): {}",
            category.name,
            total,
            if total == 1 { "tool" } else { "tools" },
            reads,
            total - reads,
            category.summary
        );
    }
    block.push_str(
        "- Every tool, one line each, is in `skills/sylvode-mcp/reference/tools.md`; the hand-written skill is \
         `skills/sylvode-mcp/SKILL.md`. Both are generated or checked by `sylvode-skillgen`.",
    );
    block
}

/// Replaces the text between the markers of the generated block `name` in `text`.
pub fn replace_block(text: &str, name: &str, body: &str) -> Result<String, String> {
    let begin_marker = format!("<!-- BEGIN GENERATED: {name} ({GENERATED_NOTE}) -->");
    let end_marker = format!("<!-- END GENERATED: {name} -->");
    let begin = unique(text, &begin_marker)?;
    let end = unique(text, &end_marker)?;
    if end < begin {
        return Err(format!("the block {name} ends before it begins"));
    }
    let head = text.get(..begin + begin_marker.len()).unwrap_or_default();
    let tail = text.get(end..).unwrap_or_default();
    Ok(format!("{head}\n{}\n{tail}", body.trim_end_matches('\n')))
}

fn sha_prefix(text: &str) -> String {
    let digest = Sha256::digest(text.as_bytes());
    digest.iter().take(6).fold(String::new(), |mut hex, byte| {
        let _ = write!(hex, "{byte:02x}");
        hex
    })
}

/// Writes the stamp line of `SKILL.md`: the version and the first 12 hex digits of the SHA-256
/// of the file with the hash field zeroed.
fn stamp(skill_md: &str, version: &str) -> Result<String, String> {
    let start = unique(skill_md, STAMP_PREFIX)?;
    let line_end = skill_md
        .get(start..)
        .and_then(|rest| rest.find('\n'))
        .map_or(skill_md.len(), |n| start + n);
    let head = skill_md.get(..start).unwrap_or_default();
    let tail = skill_md.get(line_end..).unwrap_or_default();
    let line = |hash: &str| format!("{STAMP_PREFIX}{version} h={hash} -->");
    let hash = sha_prefix(&format!("{head}{}{tail}", line(ZERO_HASH)));
    Ok(format!("{head}{}{tail}", line(&hash)))
}

/// The sorted tool names the API tests check the agent policy registry against.
pub fn tool_names_fixture(catalogue: &Catalogue<'_>) -> String {
    let names = catalogue
        .catalog
        .iter()
        .map(|entry| entry.name)
        .collect::<BTreeSet<_>>();
    let rendered = serde_json::to_string_pretty(&names.into_iter().collect::<Vec<_>>()).unwrap_or_default();
    format!("{rendered}\n")
}

/// Every generated file, in a fixed order.
pub fn outputs(catalogue: &Catalogue<'_>, sources: &Sources) -> Result<Vec<Output>, String> {
    let skill = replace_block(&sources.skill_md, "tool-overview", &tool_overview_block(catalogue))?;
    let skill = stamp(&skill, catalogue.version)?;
    let agents_section = agents_section(catalogue, &skill)?;
    let recipes = recipes_extract(&skill)?;
    let at = |what: &str, result: Result<String, String>| result.map_err(|error| format!("{what}: {error}"));
    Ok(vec![
        Output {
            path: paths::SKILL_MD,
            content: skill,
        },
        Output {
            path: paths::TOOLS_MD,
            content: tools_reference(catalogue),
        },
        Output {
            path: paths::AGENTS_SECTION,
            content: agents_section,
        },
        Output {
            path: paths::SERVER_INSTRUCTIONS,
            content: server_instructions(catalogue),
        },
        Output {
            path: paths::RECIPES,
            content: recipes,
        },
        Output {
            path: paths::SERVER_README,
            content: at(
                paths::SERVER_README,
                replace_block(&sources.server_readme, "tool-table", &tool_table_block(catalogue)),
            )?,
        },
        Output {
            path: paths::SERVER_AGENTS,
            content: at(
                paths::SERVER_AGENTS,
                replace_block(
                    &sources.server_agents,
                    "tool-overview",
                    &agents_overview_block(catalogue),
                ),
            )?,
        },
        Output {
            path: paths::ROOT_README,
            content: at(
                paths::ROOT_README,
                replace_block(
                    &sources.root_readme,
                    "tool-count",
                    &tool_count_block(catalogue, "skills/sylvode-mcp/reference/tools.md"),
                ),
            )?,
        },
        Output {
            path: paths::DOCS_README,
            content: at(
                paths::DOCS_README,
                replace_block(
                    &sources.docs_readme,
                    "tool-count",
                    &tool_count_block(catalogue, "../skills/sylvode-mcp/reference/tools.md"),
                ),
            )?,
        },
        Output {
            path: paths::TOOL_NAMES_FIXTURE,
            content: tool_names_fixture(catalogue),
        },
    ])
}

