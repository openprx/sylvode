//! `sylvode-skillgen`: the generator behind `skills/sylvode-mcp`.
//!
//! The skill directory is the single hand-written source for everything an agent is told about
//! the Sylvode MCP server. Every tool list, count and category table anywhere else is generated
//! from the tool catalogue ([`crate::tools::catalog`]) and checked in; `--check` regenerates in
//! memory and fails with a diff when a checked-in file differs, so an MCP change that the skill
//! text did not follow cannot merge. The generator is deterministic: the same inputs give the
//! same bytes.
//!
//! This module is pure (no file or process access); `src/bin/skillgen.rs` reads and writes the
//! files. All inputs are passed in, so the tests drive it with a fixture catalogue.

use std::collections::BTreeSet;
use std::fmt::Write as _;

use sha2::{Digest, Sha256};

use crate::tools::catalog::{Access, Category, ToolMeta};

/// Repository paths of the files this module reads or writes, relative to the repository root.
pub mod paths {
    pub const SKILL_MD: &str = "skills/sylvode-mcp/SKILL.md";
    pub const INSTALL_MD: &str = "skills/sylvode-mcp/recipes/install.md";
    pub const TOOLS_MD: &str = "skills/sylvode-mcp/reference/tools.md";
    pub const AGENTS_SECTION: &str = "skills/sylvode-mcp/generated/AGENTS.section.md";
    pub const SERVER_INSTRUCTIONS: &str = "skills/sylvode-mcp/generated/server-instructions.md";
    pub const RECIPES: &str = "skills/sylvode-mcp/generated/recipes.md";
    pub const LINT_ALLOW: &str = "skills/sylvode-mcp/.lint-allow";
    pub const SERVER_README: &str = "apps/mcp-server/README.md";
    pub const SERVER_AGENTS: &str = "apps/mcp-server/AGENTS.md";
    pub const ROOT_README: &str = "README.md";
    pub const DOCS_README: &str = "docs/README.md";
    pub const TOOL_NAMES_FIXTURE: &str = "apps/api/tests/fixtures/mcp-tool-names.json";
}

const GENERATED_NOTE: &str = "sylvode-skillgen; do not edit";
const STAMP_PREFIX: &str = "<!-- sylvode-skill v=";
const ZERO_HASH: &str = "000000000000";
const AGENTS_BEGIN: &str = "<!-- agents:begin -->";
const AGENTS_END: &str = "<!-- agents:end -->";
const SERVER_INSTRUCTIONS_LINES: std::ops::RangeInclusive<usize> = 15..=25;
const OVERVIEW_BLOCK_MAX_LINES: usize = 60;
const SUMMARY_MAX_CHARS: usize = 120;

/// The tool catalogue the outputs are derived from.
pub struct Catalogue<'a> {
    /// The workspace version, written into the stamp of `SKILL.md`.
    pub version: &'a str,
    pub categories: &'a [Category],
    pub catalog: &'a [ToolMeta],
}

/// The checked-in files the generator reads (and whose generated blocks it rewrites).
pub struct Sources {
    pub skill_md: String,
    pub server_readme: String,
    pub server_agents: String,
    pub root_readme: String,
    pub docs_readme: String,
}

/// One generated file: its path relative to the repository root and its full content.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Output {
    pub path: &'static str,
    pub content: String,
}

fn counts(catalogue: &Catalogue<'_>, category: &str) -> (usize, usize) {
    let entries = catalogue.catalog.iter().filter(|entry| entry.category == category);
    let reads = entries.clone().filter(|entry| entry.access == Access::Read).count();
    (reads, entries.count())
}

fn category_table(catalogue: &Catalogue<'_>) -> String {
    let mut table = String::from("| Category | Tools | Read | Write | Covers |\n|---|---:|---:|---:|---|\n");
    for category in catalogue.categories {
        let (reads, total) = counts(catalogue, category.name);
        let _ = writeln!(
            table,
            "| `{}`: {} | {} | {} | {} | {} |",
            category.name,
            category.title,
            total,
            reads,
            total - reads,
            category.summary
        );
    }
    table
}

fn tool_sentence(catalogue: &Catalogue<'_>) -> String {
    format!(
        "{} tools in {} categories",
        catalogue.catalog.len(),
        catalogue.categories.len()
    )
}

const RULE: &str = "Find a tool with `sylvode_search`, call a `read` tool with `sylvode_read` and a `write` tool with \
                    `sylvode_write`. The five task tools are called directly.";

/// The block `tool-overview` of `SKILL.md`.
pub fn tool_overview_block(catalogue: &Catalogue<'_>) -> String {
    let mut block = format!(
        "Sylvode has {}. In search mode (the default) the tool list holds only `sylvode_overview`, \
         `sylvode_search`, `sylvode_read`, `sylvode_write` and the task tools. {RULE}\n\n",
        tool_sentence(catalogue)
    );
    block.push_str(&category_table(catalogue));
    block
}

/// `reference/tools.md`: every tool, one line each, grouped by category.
pub fn tools_reference(catalogue: &Catalogue<'_>) -> String {
    let mut text = format!(
        "# Sylvode tools\n\nGenerated by sylvode-skillgen from the tool catalogue; do not edit. {}.\n\n\
         In search mode (the default) the tool list holds only the entry tools and the task tools. {RULE} In full mode, an explicit choice of whoever configures the \
         server, every tool is listed by its own name and called directly.\n",
        tool_sentence(catalogue)
    );
    for category in catalogue.categories {
        let _ = write!(
            text,
            "\n## {}: {}\n\n{}\n\n",
            category.name, category.title, category.summary
        );
        if category.name == "tasks" {
            text.push_str(
                "Call these directly by name; they are not called through `sylvode_read` or `sylvode_write`.\n\n",
            );
        }
        for entry in catalogue.catalog.iter().filter(|entry| entry.category == category.name) {
            let _ = writeln!(
                text,
                "- `{}` ({}) — {}",
                entry.name,
                entry.access.as_str(),
                entry.summary
            );
        }
    }
    text
}

/// The text between the `agents:begin` and `agents:end` markers of `SKILL.md`.
fn agents_segment(skill_md: &str) -> Result<&str, String> {
    let begin = unique(skill_md, AGENTS_BEGIN)?;
    let end = unique(skill_md, AGENTS_END)?;
    if end < begin {
        return Err(format!("{AGENTS_END} comes before {AGENTS_BEGIN}"));
    }
    skill_md
        .get(begin + AGENTS_BEGIN.len()..end)
        .ok_or_else(|| "the agents markers do not delimit text".to_string())
}

fn unique(text: &str, needle: &str) -> Result<usize, String> {
    let mut found = text.match_indices(needle).map(|(index, _)| index);
    match (found.next(), found.next()) {
        (Some(index), None) => Ok(index),
        (None, _) => Err(format!("`{needle}` is missing")),
        (Some(_), Some(_)) => Err(format!("`{needle}` appears more than once")),
    }
}

/// Moves every Markdown heading outside a code fence by `delta` levels (never below one `#`).
fn shift_headings(text: &str, deeper: bool) -> String {
    let mut fenced = false;
    let mut shifted = String::with_capacity(text.len() + 64);
    for line in text.lines() {
        if line.trim_start().starts_with("```") {
            fenced = !fenced;
        }
        if !fenced && line.starts_with('#') {
            if deeper {
                shifted.push('#');
                shifted.push_str(line);
            } else if line.starts_with("##") {
                shifted.push_str(line.get(1..).unwrap_or(line));
            } else {
                shifted.push_str(line);
            }
        } else {
            shifted.push_str(line);
        }
        shifted.push('\n');
    }
    shifted
}

/// `generated/AGENTS.section.md`: the body the runner writes into the managed section of a
/// project's `AGENTS.md` (codex and opencode).
pub fn agents_section(catalogue: &Catalogue<'_>, skill_md: &str) -> Result<String, String> {
    let segment = agents_segment(skill_md)?;
    let mut text = String::from(
        "## Sylvode MCP\n\nSylvode tasks and data are reached through the Sylvode MCP server. \
         Follow this section for every message that starts with \"[Sylvode task]\" or \"[Sylvode reminder]\".\n",
    );
    text.push_str(&shift_headings(segment.trim_matches('\n'), true));
    let _ = write!(
        text,
        "\n### Tool categories\n\nSylvode has {}. {RULE}\n\n{}",
        tool_sentence(catalogue),
        category_table(catalogue)
    );
    Ok(text)
}

/// `generated/recipes.md`: the "Recipes" part of `SKILL.md`, served as `sylvode://guides/workflows`.
pub fn recipes_extract(skill_md: &str) -> Result<String, String> {
    let segment = agents_segment(skill_md)?;
    let start = unique(segment, "## Recipes")?;
    let recipes = segment.get(start + "## Recipes".len()..).unwrap_or_default();
    let mut text = String::from("# Common workflows\n\n");
    text.push_str(&shift_headings(recipes.trim_matches('\n'), false));
    Ok(text)
}

/// `generated/server-instructions.md`: the `instructions` of `initialize`. The text holds for both
/// tool modes: it names what to do with the tools the list shows.
pub fn server_instructions(catalogue: &Catalogue<'_>) -> String {
    let categories = catalogue
        .categories
        .iter()
        .map(|category| category.name)
        .collect::<Vec<_>>()
        .join(", ");
    format!(
        "Sylvode MCP server. Everything here is about Sylvode tasks and data.\n\
         \n\
         Tasks. A message that starts with \"[Sylvode task]\" or \"[Sylvode reminder]\" names a task id and an attempt.\n\
         Every such message is complete on its own; do not rely on earlier conversation.\n\
         1. sylvode_task_get with task_id and attempt: read the source and the reply_policy.\n\
         2. sylvode_task_ack with a plan of one to five lines, then start work at once.\n\
         3. sylvode_task_progress at each milestone and at least every 10 minutes.\n\
         4. Finish with sylvode_task_complete (outcome, summary) or sylvode_task_fail (reason).\n\
         Sylvode posts the reply where the task came from. Do not post your own.\n\
         \n\
         Other tools. If sylvode_search is listed, find tools with it, call a read tool with sylvode_read and a write \
         tool with sylvode_write, as {{\"tool\": name, \"arguments\": {{...}}}}. If the list holds the tools themselves, \
         call them by name. The task tools are always called directly.\n\
         If sylvode_write answers that writes are disabled, do not retry. A refusal that names the project agent \
         policy is final.\n\
         \n\
         Categories: {categories}.\n\
         Read the resource sylvode://skills/sylvode-mcp for the full guide and sylvode://skills/sylvode-mcp/tools for \
         every tool.\n"
    )
}

